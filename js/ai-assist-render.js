/* AI assist: panel rendering. Attaches to window.AiAssist.render; the
   orchestrator in js/ai-assist.js wires events and assembles the public API.
   Loads after js/ai-assist-client.js.

   Everything the model returns is untrusted text and goes through escapeHtml
   before it reaches innerHTML. This is the only surface in the tool that
   renders content nobody in this repo wrote, so it is the one place where a
   missed escape actually matters. The one exception is the page preview, which
   goes through renderPageMain() — the same escaping-audited renderer the real
   mockup uses (see tests/page-render.test.js). */
;(function mountAiAssistRender() {
  if (typeof window === 'undefined') return

  const PANEL_ID = 'aiAssistPanel'
  const HOST_ID = 'reviewWorkspaceAssist'

  /** Panel state. Not persisted: a draft is deliberately ephemeral. */
  const state = {
    capabilities: null,
    status: '',
    busy: false,
    result: null,
    error: '',
    // The reviewer's request text, mirrored here on every render. The panel
    // re-renders wholesale on any state change, which replaces the textarea —
    // so without this, clicking Generate would blank the box, and a refusal,
    // timeout, or cancel would take the whole request down with it.
    prompt: '',
    includePage: true,
  }

  const escapeHtml = (value) => window.utils.escapeHtml(value)

  function getHost() {
    return document.getElementById(HOST_ID)
  }

  /**
   * Derive a page key from a slug, matching the camelCase convention in
   * js/page-data.js. Only used to name the downloaded module — the reviewer
   * renames it if they disagree.
   * @param {string} slug
   * @returns {string}
   */
  function pageKeyFromSlug(slug) {
    const tail = String(slug || 'generatedPage')
      .split('/')
      .filter(Boolean)
      .pop()
    const words = String(tail)
      .replace(/[^a-zA-Z0-9]+/g, ' ')
      .trim()
      .split(/\s+/)
    if (!words.length || !words[0]) return 'generatedPage'
    return words
      .map((word, index) =>
        index === 0
          ? word.toLowerCase()
          : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase()
      )
      .join('')
  }

  /**
   * Build a `pages/*.js` module body for a generated page.
   *
   * Produced for DOWNLOAD ONLY. Nothing in this tool writes it to disk —
   * review layers must never write back to page sources, and the standards
   * manual forbids automated publication. The reviewer saves it, reads it, and
   * decides.
   * @param {object} page
   * @param {string} disclosure
   * @returns {string}
   */
  function buildPageModuleSource(page, disclosure) {
    const key = pageKeyFromSlug(page.slug)
    return `// ${disclosure}
// Generated by the HHVC AI assist panel. Review every claim against HHVC
// source documents before this goes anywhere near a real page.
window.HHVC_PAGES = window.HHVC_PAGES || {}
window.HHVC_PAGES['${key}'] = ${JSON.stringify(page, null, 2)}
`
  }

  /** @returns {string} the config form, always shown so settings stay reachable. */
  function renderSettings() {
    const config = window.AiAssist.client.readConfig()
    return `
      <details class="ai-assist-settings"${window.AiAssist.client.isConfigured() ? '' : ' open'}>
        <summary>AI server settings</summary>
        <label class="field-help" for="aiAssistApiUrl">Server URL</label>
        <input id="aiAssistApiUrl" class="sync-config-input" type="text"
          placeholder="https://your-app.up.railway.app" value="${escapeHtml(config.apiUrl)}" />
        <label class="field-help" for="aiAssistApiToken">API token</label>
        <input id="aiAssistApiToken" class="sync-config-input" type="password"
          placeholder="Bearer token" value="${escapeHtml(config.apiToken)}" />
        <button type="button" class="tool-btn secondary-tool" id="aiAssistSaveSettings">
          Save AI settings
        </button>
      </details>`
  }

  /** @returns {string} whichever explanation applies before a draft can be made. */
  function renderUnavailable() {
    if (!window.AiAssist.client.isConfigured()) {
      return `<p class="field-help">Enter a server URL and token above, then save, to use AI assist.
        The tool works normally without it.</p>`
    }
    if (state.capabilities && !state.capabilities.providers?.claude) {
      return `<p class="field-help">The server is reachable but has no model provider configured
        (<code>ANTHROPIC_API_KEY</code> is unset). Drafting is unavailable until it is set.</p>`
    }
    return ''
  }

  /** @returns {string} the request form. */
  function renderForm() {
    const ready =
      window.AiAssist.client.isConfigured() && state.capabilities?.providers?.claude === true
    const disabled = !ready || state.busy ? ' disabled' : ''
    return `
      <div class="ai-assist-form">
        <label class="field-help" for="aiAssistPrompt">What should the draft cover?</label>
        <textarea id="aiAssistPrompt" rows="4"
          placeholder="Draft an Information page explaining what happens after a bed bug report."
          ${disabled ? 'disabled' : ''}>${escapeHtml(state.prompt)}</textarea>
        <label class="ai-assist-checkbox">
          <input type="checkbox" id="aiAssistIncludePage"${state.includePage ? ' checked' : ''} ${disabled ? 'disabled' : ''} />
          <span>Use the page open in the mockup as context</span>
        </label>
        <div class="ai-assist-actions">
          <button type="button" class="tool-btn" id="aiAssistGenerate"${disabled}>
            ${state.busy ? 'Generating…' : 'Generate draft'}
          </button>
          ${
            state.busy
              ? '<button type="button" class="tool-btn secondary-tool" id="aiAssistCancel">Cancel</button>'
              : ''
          }
        </div>
        ${state.status ? `<p class="field-help">${escapeHtml(state.status)}</p>` : ''}
        ${state.error ? `<p class="ai-assist-error">${escapeHtml(state.error)}</p>` : ''}
      </div>`
  }

  /** @returns {string} the validation verdict and any issues, listed in full. */
  function renderVerdict(result) {
    const issues = result.issues || []
    if (result.valid) {
      return `<p class="ai-assist-verdict pass">Passes every check this repo enforces${
        result.attempts > 1 ? `, after ${escapeHtml(String(result.attempts))} attempts` : ''
      }.</p>`
    }
    return `
      <div class="ai-assist-verdict fail">
        <p><strong>${escapeHtml(String(issues.length))} issue(s) would fail validation.</strong>
        The draft is shown anyway so you can judge and fix it.</p>
        <ul>${issues.map((issue) => `<li>${escapeHtml(issue)}</li>`).join('')}</ul>
      </div>`
  }

  /** @returns {string} the generated page, rendered by the real mockup renderer. */
  function renderResult() {
    if (!state.result) return ''
    const result = state.result
    const page = result.result

    // renderPageMain is a pure page-object -> HTML function. Calling it here
    // renders the draft WITHOUT touching pageData, DATA.order, or the mockup:
    // the preview is a dead end by construction, which is what keeps a draft
    // from ever becoming site content by accident.
    let preview = ''
    try {
      preview = renderPageMain(page)
    } catch (error) {
      preview = `<p class="ai-assist-error">Could not preview this draft: ${escapeHtml(
        error?.message || 'unknown error'
      )}</p>`
    }

    return `
      <section class="ai-assist-result">
        <p class="ai-assist-disclosure">${escapeHtml(result.disclosure || '')}</p>
        ${renderVerdict(result)}
        <div class="ai-assist-meta">
          <span>${escapeHtml(result.provider || '')} · ${escapeHtml(result.model || '')}</span>
          <span>${escapeHtml(String(result.attempts || 1))} attempt(s)</span>
        </div>
        <div class="ai-assist-result-actions">
          <button type="button" class="tool-btn secondary-tool" id="aiAssistCopyJson">
            Copy page JSON
          </button>
          <button type="button" class="tool-btn secondary-tool" id="aiAssistDownload">
            Download pages module
          </button>
        </div>
        <h4>Preview</h4>
        <div class="ai-assist-preview">${preview}</div>
      </section>`
  }

  /** Create the panel container on first open. */
  function mountPanel() {
    const existing = document.getElementById(PANEL_ID)
    if (existing) return existing
    const host = getHost()
    if (!host) return null
    const panel = document.createElement('section')
    panel.id = PANEL_ID
    panel.className = 'ai-assist-panel'
    panel.setAttribute('aria-label', 'AI assist')
    host.appendChild(panel)
    return panel
  }

  /**
   * Stop preview links from navigating the real mockup.
   *
   * renderPageMain emits the same `data-render-target` buttons the live page
   * uses, and the click handler in js/page-render.js is bound to `document` —
   * so a card or inline link in a DRAFT would call window.renderPage() and move
   * the reviewer off the page they were reviewing. Rewriting the attribute to
   * `data-render-inert` keeps the button in the same handler branch (so the
   * click is still swallowed rather than doing something else surprising) while
   * leaving it with no target to navigate to. Accordion toggles are untouched:
   * they resolve within the preview's own DOM and are worth keeping usable.
   * @param {Element} panel
   * @returns {void}
   */
  function neutralizePreviewLinks(panel) {
    const preview = panel.querySelector('.ai-assist-preview')
    if (!preview) return

    for (const node of preview.querySelectorAll('[data-render-target]')) {
      node.removeAttribute('data-render-target')
      node.setAttribute('data-render-inert', '')
      node.setAttribute('aria-disabled', 'true')
      node.title = 'Preview only — this link does not navigate.'
    }

    // Real anchors too, not just the in-mockup buttons. renderPageMain emits
    // `<a href>` for every external URL — cards, service tiles, buttons,
    // inline markdown links, the print-version link — plus `href="#..."` for
    // the on-page contents list. A draft's `url` and `buttonUrl` values come
    // from the MODEL, so leaving them live means one click on unreviewed
    // content opens a model-invented destination. `aria-disabled` does not
    // stop an anchor; only removing href does.
    for (const anchor of preview.querySelectorAll('a[href]')) {
      // Keep the original visible for a reviewer judging the draft — the
      // destination is part of what they are reviewing — but make it inert.
      anchor.setAttribute('data-preview-href', anchor.getAttribute('href') || '')
      anchor.removeAttribute('href')
      anchor.removeAttribute('target')
      anchor.setAttribute('role', 'link')
      anchor.setAttribute('aria-disabled', 'true')
      anchor.title = 'Preview only — this link does not navigate.'
    }
  }

  /** Render everything. Cheap enough to redo wholesale on any state change. */
  function renderPanel() {
    const panel = mountPanel()
    if (!panel) return
    panel.innerHTML = `
      <h3>AI assist</h3>
      <p class="review-decision-note">
        Drafts content for review. Output is never saved, never published, and never changes a
        review decision. Every draft is checked against the same schema, link, and plain-language
        rules CI enforces.
      </p>
      ${renderSettings()}
      ${renderUnavailable()}
      ${renderForm()}
      ${renderResult()}`
    neutralizePreviewLinks(panel)
  }

  const api = {
    PANEL_ID,
    HOST_ID,
    state,
    pageKeyFromSlug,
    buildPageModuleSource,
    mountPanel,
    renderPanel,
    neutralizePreviewLinks,
    getHost,
  }

  window.AiAssist = window.AiAssist || {}
  window.AiAssist.render = api

  if (typeof module !== 'undefined' && module.exports) module.exports = api
})()
